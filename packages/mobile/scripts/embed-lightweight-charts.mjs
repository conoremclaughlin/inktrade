#!/usr/bin/env node
/**
 * Inlines the lightweight-charts standalone bundle into a TS module so the
 * candlestick WebView can run fully offline.
 *
 * The WebView has no bundler and no node_modules, so the library has to be
 * injected as source text. Pulling it from a CDN instead would make charts
 * fail whenever the network does — and the rest of the app already caches.
 *
 * Mirrors packages/mobile/scripts/embed-pdfjs.mjs in inkread.
 */
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';

const __dirname = dirname(fileURLToPath(import.meta.url));
const require = createRequire(import.meta.url);

const OUT_FILE = join(__dirname, '..', 'src', 'charts', 'lightweightChartsEmbedded.ts');

function resolveStandaloneBundle() {
  // Resolve through the package so yarn's hoisting decides the location, not a
  // hardcoded path that breaks when the workspace layout changes.
  //
  // Resolve package.json rather than the package root: lightweight-charts'
  // exports map defines only an "import" condition for ".", so require.resolve
  // on the root throws ERR_PACKAGE_PATH_NOT_EXPORTED. "./package.json" is
  // exported explicitly, so it resolves under both CJS and ESM.
  const pkgJson = require.resolve('lightweight-charts/package.json');
  const candidate = join(dirname(pkgJson), 'dist', 'lightweight-charts.standalone.production.js');
  if (!existsSync(candidate)) {
    throw new Error(`lightweight-charts standalone bundle not found at ${candidate}`);
  }
  return candidate;
}

function main() {
  const bundlePath = resolveStandaloneBundle();
  const source = readFileSync(bundlePath, 'utf-8');

  // Embed as a base64 payload: the bundle contains backticks, ${...} and other
  // sequences that would need fragile escaping inside a template literal.
  const encoded = Buffer.from(source, 'utf-8').toString('base64');

  const out = `// AUTO-GENERATED by scripts/embed-lightweight-charts.mjs — do not edit.
// Source: lightweight-charts standalone production bundle.
/* eslint-disable */
export const LIGHTWEIGHT_CHARTS_BASE64 = '${encoded}';
`;

  mkdirSync(dirname(OUT_FILE), { recursive: true });

  // Skip the write when unchanged so Metro doesn't see a phantom file change
  // on every start and reload the app for no reason.
  if (existsSync(OUT_FILE) && readFileSync(OUT_FILE, 'utf-8') === out) {
    console.log('[embed-lightweight-charts] up to date');
    return;
  }

  writeFileSync(OUT_FILE, out);
  console.log(
    `[embed-lightweight-charts] wrote ${(encoded.length / 1024).toFixed(0)}KB from ${bundlePath}`,
  );
}

main();
